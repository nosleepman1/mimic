package faker

import (
	"fmt"
	"math/rand"
	"strings"
	"time"

	"github.com/google/uuid"
	"github.com/teranga-host/mimic/internal/domain"
)

// Generator génère des données réalistes à la volée à partir de schémas ou de noms de champs
type Generator struct{}

func NewGenerator() *Generator {
	return &Generator{}
}

// GenerateFromSchema crée un objet ou une valeur factice conforme au schéma
func (g *Generator) GenerateFromSchema(s *domain.Schema, fieldNameHint string) interface{} {
	if s == nil {
		return g.GuessFromFieldName(fieldNameHint)
	}

	if s.Example != nil {
		return s.Example
	}

	if len(s.Enum) > 0 {
		return s.Enum[rand.Intn(len(s.Enum))]
	}

	switch s.Type {
	case domain.TypeObject:
		result := make(map[string]interface{})
		for propName, propSchema := range s.Properties {
			result[propName] = g.GenerateFromSchema(propSchema, propName)
		}
		return result

	case domain.TypeArray:
		count := 3
		items := make([]interface{}, count)
		for i := 0; i < count; i++ {
			items[i] = g.GenerateFromSchema(s.Items, fieldNameHint)
		}
		return items

	case domain.TypeUUID:
		return uuid.New().String()

	case domain.TypeEmail:
		name := strings.ToLower(strings.ReplaceAll(RandomFullName(), " ", "."))
		return fmt.Sprintf("%s@example.com", name)

	case domain.TypeName:
		return RandomFullName()

	case domain.TypePhone, domain.TypePhoneSN:
		return RandomPhoneSN()

	case domain.TypeXOF:
		return RandomCurrencyXOF()

	case domain.TypeInteger:
		return rand.Intn(100) + 1

	case domain.TypeFloat:
		return float64(rand.Intn(10000)) / 100.0

	case domain.TypeBoolean:
		return rand.Intn(2) == 1

	case domain.TypeDateISO:
		return time.Now().UTC().Format(time.RFC3339)

	case domain.TypeAvatar:
		return fmt.Sprintf("https://i.pravatar.cc/300?u=%s", uuid.New().String())

	case domain.TypeSentence:
		return "This is an automated dynamic mock response generated by Mimic engine."

	case domain.TypeString:
		if s.Format == "uuid" {
			return uuid.New().String()
		}
		if s.Format == "email" {
			name := strings.ToLower(strings.ReplaceAll(RandomFullName(), " ", "."))
			return fmt.Sprintf("%s@example.com", name)
		}
		if s.Format == "date-time" || s.Format == "date" {
			return time.Now().UTC().Format(time.RFC3339)
		}
		return g.GuessFromFieldName(fieldNameHint)

	default:
		return g.GuessFromFieldName(fieldNameHint)
	}
}

// GuessFromFieldName déduit intelligemment le type de données à partir du nom du champ
func (g *Generator) GuessFromFieldName(name string) interface{} {
	lower := strings.ToLower(name)

	switch {
	case strings.Contains(lower, "id") || lower == "uuid":
		return uuid.New().String()

	case strings.Contains(lower, "email") || strings.Contains(lower, "mail"):
		nameFormatted := strings.ToLower(strings.ReplaceAll(RandomFullName(), " ", "."))
		return fmt.Sprintf("%s@example.com", nameFormatted)

	case strings.Contains(lower, "phone") || strings.Contains(lower, "tel") || strings.Contains(lower, "mobile"):
		return RandomPhoneSN()

	case strings.Contains(lower, "name") || strings.Contains(lower, "nom") || strings.Contains(lower, "prenom") || strings.Contains(lower, "author") || strings.Contains(lower, "user"):
		return RandomFullName()

	case strings.Contains(lower, "amount") || strings.Contains(lower, "price") || strings.Contains(lower, "balance") || strings.Contains(lower, "solde") || strings.Contains(lower, "total"):
		return RandomCurrencyXOF()

	case strings.Contains(lower, "city") || strings.Contains(lower, "ville"):
		return RandomCity()

	case strings.Contains(lower, "company") || strings.Contains(lower, "entreprise") || strings.Contains(lower, "org"):
		return RandomCompany()

	case strings.Contains(lower, "department") || strings.Contains(lower, "service"):
		return RandomDepartment()

	case strings.Contains(lower, "date") || strings.Contains(lower, "_at") || strings.Contains(lower, "time"):
		return time.Now().UTC().Format(time.RFC3339)

	case strings.Contains(lower, "avatar") || strings.Contains(lower, "image") || strings.Contains(lower, "photo") || strings.Contains(lower, "picture"):
		return fmt.Sprintf("https://i.pravatar.cc/300?u=%s", uuid.New().String())

	case strings.Contains(lower, "status") || strings.Contains(lower, "state"):
		statuses := []string{"active", "pending", "completed", "archived"}
		return statuses[rand.Intn(len(statuses))]

	case strings.Contains(lower, "is_") || strings.Contains(lower, "has_") || strings.Contains(lower, "active") || strings.Contains(lower, "enabled"):
		return true

	case strings.Contains(lower, "count") || strings.Contains(lower, "quantity") || strings.Contains(lower, "age") || strings.Contains(lower, "views"):
		return rand.Intn(50) + 1

	case strings.Contains(lower, "description") || strings.Contains(lower, "bio") || strings.Contains(lower, "summary") || strings.Contains(lower, "content") || strings.Contains(lower, "message"):
		return "High-performance dynamic mock response powered by Mimic."

	default:
		if name == "" {
			return "sample_value"
		}
		return fmt.Sprintf("%s_value", name)
	}
}
